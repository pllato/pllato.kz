rep('Счёт выставлен ТОО «Центр кинезиса Рудный» сверх платежей ТОО «Центр кинезиса Костанай» по Договору № BUB-2026-02 (счёт BUB-С-2026-02) и их не заменяет. Второй заказчик (Тимур) работы по Рудному не оплачивает. Гарантия по центру в Рудном — 3 месяца после сдачи.',
    'Отдельный договор с ТОО «Центр кинезиса Рудный»: стоимость 500 000 ₸, без абонентской платы. Расчёты по договорам центров в г. Уральск и г. Костанай этим счётом не затрагиваются. Гарантия — 3 месяца после сдачи. Договор действует до 31.12.2027.')
assert 'оглашени' not in s.split('<body')[1]
