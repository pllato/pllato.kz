import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {CHAT_MEMBERSHIP_GUARDS,isInactiveChatUser} from '../elc-worker/chat-membership-lifecycle.js';
const db=new DatabaseSync(':memory:');
db.exec(`CREATE TABLE users(uid TEXT PRIMARY KEY,email TEXT,active INTEGER);
CREATE TABLE team_chat_members(channel_id TEXT,user_id TEXT,role TEXT,PRIMARY KEY(channel_id,user_id));
CREATE TABLE team_chat_msgs(id TEXT,user_id TEXT,text TEXT);
INSERT INTO users VALUES ('old','old@test.kz',0),('alias','OLD@test.kz',1),('live','live@test.kz',1),('next','next@test.kz',1);
INSERT INTO team_chat_members VALUES ('group','old','admin'),('dm','alias','member'),('group','live','member'),('group','next','admin');
INSERT INTO team_chat_msgs VALUES ('msg','old','history');`);
for(const sql of CHAT_MEMBERSHIP_GUARDS)db.exec(sql);
assert.deepEqual(db.prepare('SELECT user_id FROM team_chat_members ORDER BY user_id').all().map(x=>x.user_id),['live','next']);
assert.equal(db.prepare('SELECT count(*) AS n FROM team_chat_msgs').get().n,1);
for(const uid of ['old','alias'])assert.throws(()=>db.prepare('INSERT INTO team_chat_members VALUES (?,?,?)').run('new',uid,'member'),/inactive employee/);
db.exec("UPDATE users SET active=0 WHERE uid='next'");assert.equal(db.prepare("SELECT count(*) AS n FROM team_chat_members WHERE user_id='next'").get().n,0);
db.exec("UPDATE users SET active=1 WHERE uid='next'");assert.equal(db.prepare("SELECT count(*) AS n FROM team_chat_members WHERE user_id='next'").get().n,0);
db.exec("INSERT INTO team_chat_members VALUES ('group','next','member')");
for(const sql of CHAT_MEMBERSHIP_GUARDS)db.exec(sql);
assert.equal(db.prepare('SELECT count(*) AS n FROM team_chat_members').get().n,2);
const env={DB:{prepare:sql=>({bind:uid=>({first:async()=>db.prepare(sql).get(uid)})})}};
assert.equal(await isInactiveChatUser(env,'alias'),true);assert.equal(await isInactiveChatUser(env,'live'),false);
console.log('Inactive Team membership: backfill, aliases, future deactivation, no automatic rejoin, insertion guard, history, idempotency and access check passed');
