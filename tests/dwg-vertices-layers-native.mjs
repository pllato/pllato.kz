import fs from 'node:fs';
import assert from 'node:assert/strict';
import create from '../app/stroy/dwg/vendor/pllato-executive-engine.mjs';
import reader from '../app/stroy/dwg/vendor/libredwg-web.js';
import {LibreDwg,Dwg_File_Type} from '../app/stroy/dwg/vendor/libredwg-sdk.js';
import {writeAdditions} from '../app/stroy/dwg/authoring.mjs';
const m=await create({print:()=>{},printErr:()=>{}}),r=await reader({print:()=>{},printErr:()=>{}}),sdk=LibreDwg.createByWasmInstance(r);
const read=bytes=>{const p=sdk.dwg_read_data(bytes,Dwg_File_Type.DWG);try{return sdk.convert(p);}finally{sdk.dwg_free(p);}};
const input=fs.readFileSync(process.env.DWG_CLONE_FIXTURE),original=read(input),layer=original.tables.LAYER.entries[0];
m.FS.writeFile('/in.dwg',input);assert.ok(m.ccall('pllato_open','number',['string'],['/in.dwg'])<128);
writeAdditions(m,[{type:'LINE',values:[0,0,10,10]}]);const line=m.ccall('pllato_last_handle','string',[],[]);
assert.equal(m.ccall('pllato_vertex','number',['string','number','number','number'],[line,1,20,30]),0);
writeAdditions(m,[{type:'TEXT',text:'Название',values:[210,275,5,0],align:1}]);const title=m.ccall('pllato_last_handle','string',[],[]);
assert.equal(m.ccall('pllato_layer_off','number',['string','number'],[layer.handle,1]),0);
assert.ok(m.ccall('pllato_save','number',['string'],['/out.dwg'])<128);
const saved=read(m.FS.readFile('/out.dwg'));
assert.equal(saved.entities.find(e=>e.handle===line).endPoint.x,20);assert.equal(saved.entities.find(e=>e.handle===line).endPoint.y,30);
assert.equal(saved.entities.find(e=>e.handle===title).halign,1);
assert.ok(saved.tables.LAYER.entries.find(e=>e.handle===layer.handle).off);
assert.equal(saved.tables.LAYER.entries.length,original.tables.LAYER.entries.length);
console.log('PASS exact LINE vertex, centered title, hidden layer DWG roundtrip');
