import assert from 'node:assert/strict';
import {socialAccess,normalizeSocialDay,socialSeries,socialTotalSeries,handleSocialPublications} from '../crm/worker/social-publications.js';
const admin={email:'owner@test.kz',isRoot:true},viewer={email:'view@test.kz'},editor={email:'edit@test.kz'},outsider={email:'other@test.kz'};
assert.equal(socialAccess({},outsider).view,false);
assert.equal(socialAccess({},admin).edit,true);
const config={viewers:[viewer.email],editors:[editor.email]};
assert.deepEqual(socialAccess(config,viewer),{admin:false,view:true,edit:false});
assert.equal(socialAccess(config,editor).view,true);
const now=Date.parse('2026-10-13T11:00:00Z');
assert.throws(()=>normalizeSocialDay({date:'2026-10-14',stories:1,reels:0},now));
assert.throws(()=>normalizeSocialDay({date:'2026-02-30',stories:1,reels:0},now));
assert.throws(()=>normalizeSocialDay({date:'2026-10-12',stories:1.1,reels:0},now));
assert.throws(()=>normalizeSocialDay({date:'2026-10-08',stories:1,reels:0,storiesBefore:2},now));
const day=normalizeSocialDay({date:'2026-10-08',stories:10,reels:3,storiesBefore:4,reelsBefore:1},now);
const buckets=[['2026-10-01T09:00:00Z','2026-10-08T09:00:00Z'],['2026-10-08T09:00:00Z','2026-10-15T09:00:00Z']].map(([a,b])=>({start:Date.parse(a),end:Date.parse(b)}));
assert.deepEqual(socialSeries([day],buckets).map(m=>m.series.map(p=>p.value)),[[4,6],[1,2]]);
const daily=[{start:Date.parse('2026-10-07T19:00:00Z'),end:Date.parse('2026-10-08T19:00:00Z')}];
assert.deepEqual(socialSeries([day],daily).map(m=>m.series[0].value),[10,3]);
const records=new Map([['access',{...config,revision:1}]]);
class HttpError extends Error{constructor(status,message){super(message);this.status=status}}
const deps={HttpError,get:async(e,c,id)=>structuredClone(records.get(id)),list:async()=>[day],save:async(e,item,rev)=>{if((records.get(item.id)?.revision||0)!==rev)return false;records.set(item.id,structuredClone(item));return true;}};
const req=(path,method='GET',body)=>new Request('https://test'+path,{method,...(body?{body:JSON.stringify(body)}:{})});
await assert.rejects(()=>handleSocialPublications(req('/social-publications/day?date=2026-10-08'),{},outsider,deps),e=>e.status===403);
await assert.rejects(()=>handleSocialPublications(req('/social-publications/access'),{},viewer,deps),e=>e.status===403);
await assert.rejects(()=>handleSocialPublications(req('/social-publications/day?date=2026-10-08','PUT',{...day,revision:0}),{},viewer,deps),e=>e.status===403);
const saved=await handleSocialPublications(req('/social-publications/day?date=2026-10-08','PUT',{...day,revision:0}),{},editor,deps);
assert.equal(saved.item.revision,1);assert.equal(saved.item.updatedBy,editor.email);
await assert.rejects(()=>handleSocialPublications(req('/social-publications/day?date=2026-10-08','PUT',{...day,revision:0}),{},editor,deps),e=>e.status===409);
assert.equal((await handleSocialPublications(req('/social-publications/day?date=2026-10-08'),{},viewer,deps)).item.stories,10);
