import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {meetingClientContext} from '../elc-worker/meet-client-context.js';
const db=new DatabaseSync(':memory:');
db.exec(`CREATE TABLE zoom_meetings(meeting_id TEXT,deal_id TEXT,task_id TEXT,status TEXT);
CREATE TABLE deals(id TEXT,title TEXT,contact_id TEXT,pipeline_id TEXT,stage_id TEXT,responsible_uid TEXT,custom_fields TEXT);
CREATE TABLE contacts(id TEXT,name TEXT,last_name TEXT,phones TEXT);
CREATE TABLE pipelines(id TEXT,name TEXT,stages TEXT);
CREATE TABLE users(uid TEXT,name TEXT,last_name TEXT);
CREATE TABLE tasks(id TEXT,start_date_plan TEXT,end_date_plan TEXT);
INSERT INTO zoom_meetings VALUES('crm-room','deal_1','t','ready'),('crm-empty',NULL,'t','ready');
INSERT INTO deals VALUES('deal_1','Client request','c','p','new','u',NULL);
INSERT INTO contacts VALUES('c','Ivan','Test','[{"VALUE":"+7701"}]');
INSERT INTO pipelines VALUES('p','Sales','{"new":{"name":"Meeting"}}');
INSERT INTO users VALUES('u','Anna','Manager');
INSERT INTO tasks VALUES('t','2026-11-02T16:00:00+05:00','2026-11-02T17:00:00+05:00');`);
const env={DB:{prepare(sql){return {bind(...args){return {first:async()=>db.prepare(sql).get(...args)}}}}}};
const allowed=async()=>true,denied=async()=>false;
for(const me of [null,{role:'guest'}])await assert.rejects(meetingClientContext(env,'crm-room',me,allowed),e=>e.status===403);
await assert.rejects(meetingClientContext(env,'crm-room',{role:'agent'},denied),e=>e.status===403);
const c=await meetingClientContext(env,'crm-room',{role:'agent'},allowed);
assert.deepEqual(c,{dealId:'deal_1',title:'Client request',contactName:'Ivan Test',phone:'+7701',pipeline:'Sales',stage:'Meeting',responsible:'Anna Manager',startTime:'2026-11-02T16:00:00+05:00',endTime:'2026-11-02T17:00:00+05:00'});
assert.equal(await meetingClientContext(env,'crm-empty',{role:'agent'},allowed),null);
db.exec('DELETE FROM contacts; DELETE FROM pipelines; DELETE FROM users; DELETE FROM tasks;');
const sparse=await meetingClientContext(env,'crm-room',{role:'admin'},allowed);assert.equal(sparse.title,'Client request');assert.equal(sparse.phone,'');
await assert.rejects(meetingClientContext(env,'missing',{role:'admin'},allowed),e=>e.status===404);
db.exec("UPDATE deals SET custom_fields='{\"firstZoomAt\":\"2026-11-02T16:00:00\"}'; UPDATE zoom_meetings SET task_id='deal_room:deal_1' WHERE meeting_id='crm-room';");
assert.equal((await meetingClientContext(env,'crm-room',{role:'agent'},allowed)).startTime,'2026-11-02T16:00:00');
console.log('Client context: access, allowlist, joins, missing fields passed');
