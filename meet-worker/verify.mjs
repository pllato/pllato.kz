globalThis.fetch=async(url, options)=>{
  if(url.includes('rec-init')) return Response.json({uploadId:'test-upload'});
  if(url.includes('rec-part')){
    const pn=Number(url.split('/').pop());
    requests.push({pn,size:options.body.size});
    if(failures-->0) return new Response('offline',{status:503});
    return Response.json({partNumber:pn,etag:'etag-'+pn});
  }
  if(url.includes('rec-complete')) return Response.json({ok:true,size:13*MiB});
  return Response.json({ok:true});
};
